// ── Result type ────────────────────────────────────────────────────────
//
// Every mutator returns the same envelope. `ok:false` always carries a
// machine-readable `reason` AND a `blockers` list when the refusal is
// caused by dependent records — the UI needs to name them, not just say no.

export type MdReason =
  | 'missing-name'
  | 'duplicate-name'
  | 'duplicate-id'
  | 'not-found'
  | 'missing-company'
  | 'company-not-found'
  | 'has-dependents'
  | 'invalid-order'
  | 'missing-currency'
  | 'invalid-currency'
  /** SPRINT 2 — archive guards. */
  | 'already-archived'
  | 'not-archived'
  | 'has-active-children';

export interface MdResult<T> {
  ok: boolean;
  reason?: MdReason;
  record?: T;
  /** Human-readable dependents that blocked a delete. */
  blockers?: string[];
}

// ── Storage ────────────────────────────────────────────────────────────

function readJson<T>(key: string, fallback: T): T {
  try {
    const raw = localStorage.getItem(key);
    if (!raw) return fallback;
    const parsed = JSON.parse(raw);
    return parsed ?? fallback;
  } catch {
    return fallback;
  }
}

function writeJson(key: string, value: unknown): void {
  try {
    localStorage.setItem(key, JSON.stringify(value));
  } catch {
    /* quota — same policy as every other store in the platform */
  }
}

const nowIso = () => new Date().toISOString();

/**
 * Id generator.
 *
 * Prefixed and time-ordered so two ids minted in the same millisecond still
 * differ by their random tail, and so an id is recognisable in storage.
 * `createCompany`/`createSector` additionally REJECT a collision rather than
 * trusting this to be unique — see the duplicate-id guard.
 */
function mintId(prefix: string): string {
  return `${prefix}-${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;
}

/** Case-insensitive, whitespace-insensitive name comparison. */
function sameName(a: string, b: string): boolean {
  return a.trim().toLowerCase() === b.trim().toLowerCase();
}

// ── Normalisation ──────────────────────────────────────────────────────
//
// Anything read from storage is coerced into shape. A hand-edited or
// half-migrated record can never crash a consumer.

const RISKS: RiskRating[] = ['Low', 'Medium', 'High', 'Critical'];
const COMPLIANCES: Compliance[] = ['Compliant', 'Non-compliant', 'Partial'];

function cleanCompany(v: any): Company | null {
  const id = String(v?.id ?? '').trim();
  const name = String(v?.name ?? '').trim();
  if (!id || !name) return null;
  const status = (['Active', 'Paused', 'Archived'] as const)
    .includes(v?.status) ? v.status as EntityStatus : 'Active';
  return {
    id,
    name,
    nameAr: v?.nameAr ? String(v.nameAr) : undefined,
    logoUrl: v?.logoUrl ? String(v.logoUrl) : undefined,
    status,
    portfolioValue: Number.isFinite(Number(v?.portfolioValue))
      ? Number(v.portfolioValue) : 0,
    sectors: Number(v?.sectors) || 0,
    projects: Number(v?.projects) || 0,
    riskRating: RISKS.includes(v?.riskRating) ? v.riskRating : 'Low',
    compliance: COMPLIANCES.includes(v?.compliance) ? v.compliance : 'Compliant',
    // Modal-owned branding. Preserved rather than dropped.
    description: v?.description ? String(v.description) : undefined,
    primaryColor: v?.primaryColor ? String(v.primaryColor) : undefined,
    secondaryColor: v?.secondaryColor ? String(v.secondaryColor) : undefined,
    // `country` is REQUIRED by the original interface. Empty string rather
    // than a guessed country — an invented location is worse than a blank.
    country: String(v?.country ?? ''),
    city: v?.city ? String(v.city) : undefined,
    headquarters: v?.headquarters ? String(v.headquarters) : undefined,
    reportingCurrency: v?.reportingCurrency
      ? String(v.reportingCurrency).toUpperCase().slice(0, 3) : undefined,
    timeZone: v?.timeZone ? String(v.timeZone) : undefined,
    calendar: CALENDARS.some(c => c.value === v?.calendar) ? v.calendar : undefined,
    createdAt: String(v?.createdAt ?? ''),
    createdBy: String(v?.createdBy ?? ''),
  };
}

function cleanSector(v: any, fallbackOrder: number): Sector | null {
  const id = String(v?.id ?? '').trim();
  const name = String(v?.name ?? '').trim();
  const companyId = String(v?.companyId ?? '').trim();
  if (!id || !name || !companyId) return null;
  const status = (['Active', 'Paused', 'Archived'] as const)
    .includes(v?.status) ? v.status as EntityStatus : 'Active';
  return {
    id,
    name,
    nameAr: v?.nameAr ? String(v.nameAr) : undefined,
    companyId,
    status,
    /**
     * The archive audit must survive the read. `cleanSector` rebuilds the
     * object field by field, so anything not named here is DROPPED — the
     * log would have been erased on the next load, which is the one thing
     * an append-only record must never do.
     */
    archivedAt: v?.archivedAt ? String(v.archivedAt) : undefined,
    archivedBy: v?.archivedBy ? String(v.archivedBy) : undefined,
    archiveLog: Array.isArray(v?.archiveLog)
      ? v.archiveLog
          .filter((e: any) => e && (e.action === 'archived' || e.action === 'restored'))
          .map((e: any) => ({
            action: e.action as 'archived' | 'restored',
            at: String(e.at ?? ''),
            by: String(e.by ?? 'unknown'),
            note: String(e.note ?? ''),
          }))
      : undefined,
    projectIds: Array.isArray(v?.projectIds) ? v.projectIds.map(String) : [],
    order: Number.isFinite(Number(v?.order)) ? Number(v.order) : fallbackOrder,
    defaultContractCurrency: v?.defaultContractCurrency
      ? String(v.defaultContractCurrency).toUpperCase().slice(0, 3) : undefined,
    reportingCurrency: v?.reportingCurrency
      ? String(v.reportingCurrency).toUpperCase().slice(0, 3) : undefined,
    createdAt: String(v?.createdAt ?? ''),
    createdBy: String(v?.createdBy ?? ''),
  };
}

// ── Readers ────────────────────────────────────────────────────────────

export function readCompanies(): Company[] {
  const raw = readJson<any[]>(COMPANIES_KEY, []);
  if (!Array.isArray(raw)) return [];
  return raw.map(cleanCompany).filter((x): x is Company => x !== null);
}

export function readSectors(): Sector[] {
  const raw = readJson<any[]>(SECTORS_KEY, []);
  if (!Array.isArray(raw)) return [];
  const out = raw
    .map((v, i) => cleanSector(v, i))
    .filter((x): x is Sector => x !== null);
  // Stable presentation order: by company, then by explicit order.
  return out.sort((a, b) =>
    a.companyId.localeCompare(b.companyId) || a.order - b.order);
}

// ── Reactivity ─────────────────────────────────────────────────────────
//
// PHASE 3F-UX · Task 2.
//
// Phase 3E found master data correct on disk but STALE on any page that
// was already mounted: a company rename showed on the page that made it
// and nowhere else until remount. `useProjects` had solved this properly
// with a module-level subscriber Set; master data had not.
//
// The mechanism is deliberately identical to the one already proven in
// `store.ts` — same shape, same unmount safety — rather than a second
// invented pattern. Every write in this module already funnels through
// `writeCompanies` / `writeSectors`, so notification is added at that one
// choke point and NO mutator changes. That is why the 14 call sites above
// are untouched.

type MdListener = () => void;
const listeners = new Set<MdListener>();

/**
 * Registers a listener, returns its unsubscribe.
 *
 * Version-based rather than value-based: master data is read through
 * `findCompanyById` / `fetchSectors` etc., which hit localStorage on every
 * call. Pushing a value would mean choosing WHICH of the eight readers to
 * push, so instead the listener is simply told "something changed" and
 * re-reads whatever it needs.
 */
export function subscribeMasterData(fn: MdListener): () => void {
  listeners.add(fn);
  return () => { listeners.delete(fn); };
}

/** Bumped on every committed write. The value a hook renders against. */
let mdVersion = 0;
export function masterDataVersion(): number { return mdVersion; }

function notifyMasterData(): void {
  mdVersion++;
  // Copy before iterating: a listener may unmount during the notify pass.
  Array.from(listeners).forEach(fn => {
    try { fn(); } catch { /* one bad listener must not stop the rest */ }
  });
}

/** Test hook. Not used by the app. */
export function resetMasterDataListeners(): void {
  listeners.clear();
  mdVersion = 0;
}

function writeCompanies(list: Company[]): void {
  writeJson(COMPANIES_KEY, list);
  notifyMasterData();
}

function writeSectors(list: Sector[]): void {
  writeJson(SECTORS_KEY, list);
  notifyMasterData();
}

// ── Lookups (drop-in replacements for the mock helpers) ────────────────

export function findCompanyById(id: string): Company | undefined {
  if (!id) return undefined;
  return readCompanies().find(c => c.id === id);
}

export function findSectorById(id: string): Sector | undefined {
  if (!id) return undefined;
  return readSectors().find(s => s.id === id);
}

export function findSectorsByCompany(companyId: string): Sector[] {
  if (!companyId) return [];
  return readSectors()
    .filter(s => s.companyId === companyId)
    .sort((a, b) => a.order - b.order);
}

/** Every sector, ordered. Drop-in for `fetchSectors()`. */
export function fetchSectors(): Sector[] {
  return readSectors();
}

/** Every company, ordered by name. */
export function fetchCompanies(): Company[] {
  return readCompanies().sort((a, b) => a.name.localeCompare(b.name));
}

// ── Seeding ────────────────────────────────────────────────────────────

/**
 * First-run seed from the mock modules.
 *
 * NON-DESTRUCTIVE and IDEMPOTENT. A key that already holds data is left
 * exactly as it is, so a user's edits are never overwritten by a page
 * reload. Safe to call on every start-up.
 *
 * @returns what was seeded, for logging only.
 */
export function seedMasterData(
  companies: any[], sectors: any[],
): { companies: number; sectors: number } {
  let seededCompanies = 0;
  let seededSectors = 0;

  // An EMPTY seed must not claim the slot.
  //
  // `mock/companies.fetchCompanies()` self-seeds with `(MOCK_COMPANIES, [])`
  // because it cannot import MOCK_SECTORS without a circular dependency.
  // Writing that `[]` would mark sectors as "already seeded" and the real
  // sector seed arriving moments later would be skipped — leaving a company
  // list with no sectors under it. Seeding nothing is not seeding.
  if (localStorage.getItem(COMPANIES_KEY) === null
      && Array.isArray(companies) && companies.length > 0) {
    const list = companies
      .map(c => cleanCompany({ ...c, createdAt: c?.createdAt || nowIso(), createdBy: c?.createdBy || 'seed' }))
      .filter((x): x is Company => x !== null);
    writeCompanies(list);
    seededCompanies = list.length;

    // A seeded company predates the mandatory-reporting-currency rule, so
    // it carries neither the field nor an FX settings entry. Without one,
    // `reportingCurrencyOfCompany` correctly returns '' — and a create
    // form would then offer a blank inherited currency.
    //
    // Backfilled to SAR, which is what these records ALWAYS implicitly
    // were: every seeded figure was captured in the platform base before
    // multi-currency existed. This states that fact rather than inventing
    // one, and it runs only on the first-ever seed.
    list.forEach(c => {
      if (!c.reportingCurrency) ensureReportingCurrency(c.id, 'SAR');
    });
  }

  if (localStorage.getItem(SECTORS_KEY) === null
      && Array.isArray(sectors) && sectors.length > 0) {
    // Order is assigned per company in the order the seed presents them.
    const perCompany = new Map<string, number>();
    const list = sectors
      .map(s => {
        const cid = String(s?.companyId ?? '');
        const n = perCompany.get(cid) ?? 0;
        perCompany.set(cid, n + 1);
        return cleanSector(
          { ...s, order: s?.order ?? n, createdAt: s?.createdAt || nowIso(), createdBy: s?.createdBy || 'seed' },
          n,
        );
      })
      .filter((x): x is Sector => x !== null);
    writeSectors(list);
    seededSectors = list.length;
  }

  return { companies: seededCompanies, sectors: seededSectors };
}

