/**
 * Master Data registry — Companies and Sectors.
 * Destination: src/lib/masterData.ts
 *
 * ══════════════════════════════════════════════════════════════════════
 * WHY THIS FILE EXISTS  (Phase 3F, repairing Phase 3E)
 *
 * Phase 3E found two structural breaks:
 *
 *   CRIT-3E-02  Company edits were written to `pactum-enterprise-companies`
 *               but only ONE page read that key. Twelve other consumers
 *               imported the static `MOCK_COMPANIES` array directly, so a
 *               rename was visible on exactly one screen.
 *
 *   CRIT-3E-04  Sectors had no CRUD at all. They lived in `mock/sectors.ts`
 *               with no writer, which also made it impossible to attach a
 *               newly created project to anything.
 *
 * This module becomes the SINGLE SOURCE OF TRUTH for both. The mock files
 * are demoted to first-run SEED DATA and are never written to.
 *
 * ── Why the mock modules are injected rather than imported ────────────
 *
 *   `mock/companies.ts` and `mock/sectors.ts` are not owned by this layer
 *   and are not modified by this phase. Importing them here would create a
 *   hard dependency in the opposite direction to the one we want, and would
 *   make this module untestable outside the app. Instead the app calls
 *   `seedMasterData()` once at start-up with whatever the mocks hold. If it
 *   is never called, the store simply starts empty — no crash, no guess.
 *
 * ── Relationship model (locked by the Phase 3F brief) ─────────────────
 *
 *   Company 1──n Sector 1──n Project
 *
 *   The brief states "Project creation requires Company, Sector". A project
 *   must therefore CARRY its parents. `Project.companyId` / `Project.sectorId`
 *   are the authoritative link (see `lib/data.ts`).
 *
 *   `Sector.projectIds` is RETAINED as a derived cache so the 13 existing
 *   reverse-lookup call sites keep working unchanged, but it is no longer
 *   the source of truth. `reconcile()` rebuilds it from the projects array.
 *   Where the two disagree, the project wins — it is the record that a human
 *   actually filled in.
 *
 * ── What this file does NOT do ────────────────────────────────────────
 *
 *   No money, no dates, no calculation. It stores names and parentage and
 *   refuses operations that would break referential integrity.
 * ══════════════════════════════════════════════════════════════════════
 */

const COMPANIES_KEY = 'pactum-enterprise-companies';
const SECTORS_KEY = 'pactum-enterprise-sectors';

// ── Shapes ─────────────────────────────────────────────────────────────
//
// Field names mirror exactly what the existing UI already reads, so no
// consumer needs to change: c.id · c.name · c.country · c.city · c.logoUrl
// · c.status · c.portfolioValue · c.sectors · c.projects
// and s.id · s.name · s.companyId · s.projectIds · s.status

export type EntityStatus = 'Active' | 'Paused' | 'Archived';

/**
 * Working-week calendars.
 *
 * DELIBERATELY NOT USED BY ANY CALCULATION. The Delay engine counts
 * calendar days and the EVM engine works from the project programme;
 * neither consults this. It is recorded so a company's working week is
 * documented, and so a future scheduling feature has somewhere to read it
 * from. Wiring it into Delay or EVM would change historical numbers.
 */
export type CalendarKind =
  | 'gregorian-5day'   // Mon-Fri
  | 'gregorian-6day'   // Mon-Sat
  | 'gulf-sun-thu'     // Sun-Thu
  | 'gulf-sat-thu'     // Sat-Thu
  | 'continuous';      // 7 days

export const CALENDARS: { value: CalendarKind; en: string; ar: string }[] = [
  { value: 'gulf-sun-thu',    en: 'Sunday - Thursday',  ar: 'الأحد - الخميس' },
  { value: 'gulf-sat-thu',    en: 'Saturday - Thursday', ar: 'السبت - الخميس' },
  { value: 'gregorian-5day',  en: 'Monday - Friday',    ar: 'الاثنين - الجمعة' },
  { value: 'gregorian-6day',  en: 'Monday - Saturday',  ar: 'الاثنين - السبت' },
  { value: 'continuous',      en: 'Continuous (7 days)', ar: 'مستمر (7 أيام)' },
];

export type RiskRating = 'Low' | 'Medium' | 'High' | 'Critical';
export type Compliance = 'Compliant' | 'Non-compliant' | 'Partial';

/**
 * Field-for-field compatible with the original `mock/companies.ts` shape,
 * so `CompanyCard`, `CompanyGrid` and every page keep compiling unchanged.
 * `nameAr` / `createdAt` / `createdBy` are additive.
 */
export interface Company {
  id: string;
  /** User-entered. NEVER autogenerated — see `createCompany`. */
  name: string;
  nameAr?: string;
  logoUrl?: string;
  status: EntityStatus;
  portfolioValue: number;

  /**
   * Branding and free text owned by the Company Management modal.
   *
   * PHASE 3I: the modal edits these four; before they were declared here,
   * `cleanCompany` rebuilt each record field-by-field and dropped anything
   * it did not recognise. A user could type a description, press Save, see
   * the modal close, and lose the text with no error. Verified by
   * execution, then closed.
   */
  description?: string;
  primaryColor?: string;
  secondaryColor?: string;
  /** Derived counts, refreshed by `reconcile()`. Never authoritative. */
  sectors: number;
  projects: number;
  riskRating: RiskRating;
  compliance: Compliance;
  /** Required by the original interface. */
  country: string;
  city?: string;
  headquarters?: string;

  /**
   * PHASE 3F Task 4 — REPORTING CURRENCY BELONGS ONLY TO THE COMPANY.
   *
   * The authority remains `pactum-currency-{companyId}.baseCurrency`,
   * which the FX engine owns and every conversion already reads. This
   * field is a MIRROR kept in step by `setReportingCurrency()` so the
   * company record is self-describing — a list of companies can show the
   * currency without opening the FX store for each row.
   *
   * Never write it directly. `reportingCurrencyOf()` reads the FX store,
   * not this, so the two can never diverge in a way that changes a number.
   */
  reportingCurrency?: string;

  /** IANA zone, e.g. `Asia/Riyadh`. Presentation only — no calculation. */
  timeZone?: string;
  /** Working-week calendar. Presentation and planning only. */
  calendar?: CalendarKind;

  createdAt: string;
  createdBy: string;
}

export interface Sector {
  id: string;
  /** User-entered. NEVER autogenerated. */
  name: string;
  nameAr?: string;
  companyId: string;
  status: EntityStatus;

  /**
   * Archive audit. The sector could be archived and restored, but neither
   * act left any trace — no time, no actor, no history. These record it.
   *
   * `archivedAt` / `archivedBy` describe the CURRENT archived state and
   * are cleared on restore. `archiveLog` is APPEND-ONLY and survives
   * every restore, so the fact that a sector was once archived can never
   * be erased by un-archiving it.
   */
  archivedAt?: string;
  archivedBy?: string;
  archiveLog?: { action: 'archived' | 'restored'; at: string; by: string; note: string }[];
  /**
   * DERIVED CACHE. Rebuilt from `Project.sectorId` by `reconcile()`.
   * Retained so the existing `sector.projectIds.includes(id)` call sites
   * continue to work without modification.
   */
  projectIds: string[];
  /** Display order within the parent company. Contiguous from 0. */
  order: number;

  /**
   * Task 4 — OPTIONAL default contract currency for new projects here.
   *
   * Empty means "inherit the company's reporting currency". It is a
   * DEFAULT for the create-project form, never a conversion input: once a
   * project is created its own contract currency governs, and changing
   * this later cannot restate a project that already exists.
   */
  defaultContractCurrency?: string;

  /**
   * The currency THIS SECTOR's own analytics are expressed in.
   *
   * ══════════════════════════════════════════════════════════════════
   * DISTINCT FROM `defaultContractCurrency` ABOVE, WHICH IS NOT A UNIT.
   *
   *   defaultContractCurrency  a pre-fill for the create-project form.
   *                            Never used to display or convert anything.
   *   reportingCurrency        the unit every figure on the sector's own
   *                            screens is converted into and shown in.
   *
   * The two were conflated before this field existed, which is why a
   * sector had no way to state the currency it reports in — it only had
   * a hint for a form it may never open.
   *
   * MANDATORY on creation. Absent on sectors created before the field
   * existed; `scopeCurrency()` reports that as unset rather than
   * silently substituting the company's, so a screen can ask for a
   * decision instead of inventing one.
   * ══════════════════════════════════════════════════════════════════
   */
  reportingCurrency?: string;

  createdAt: string;
  createdBy: string;
}

/** The minimum a project must expose for reconciliation. */
