export interface CreateCompanyInput {
  name: string;
  nameAr?: string;
  country?: string;
  city?: string;
  headquarters?: string;
  logoUrl?: string;
  status?: EntityStatus;
  portfolioValue?: number;
  riskRating?: RiskRating;
  compliance?: Compliance;
  /** Modal-owned branding. */
  description?: string;
  primaryColor?: string;
  secondaryColor?: string;
  /** Task 4. MANDATORY at creation — see `createCompany`. */
  reportingCurrency?: string;
  timeZone?: string;
  calendar?: CalendarKind;
  createdBy?: string;
  /** Optional explicit id, for import. Rejected if already taken. */
  id?: string;
}

/**
 * Creates a company.
 *
 * NO AUTOGENERATED NAMES. An empty or whitespace-only name is refused
 * outright rather than being replaced with "Company 4" or "Untitled" —
 * a placeholder name is indistinguishable from a real one three months
 * later, and the Phase 3E brief calls this out explicitly.
 */
export function createCompany(input: CreateCompanyInput): MdResult<Company> {
  const list = readCompanies();
  const name = (input.name ?? '').trim();

  if (!name) return { ok: false, reason: 'missing-name' };
  if (list.some(c => sameName(c.name, name))) {
    return { ok: false, reason: 'duplicate-name' };
  }

  // Task 4 — REPORTING CURRENCY IS MANDATORY.
  //
  // A company with no reporting currency cannot be reported on at all:
  // every conversion resolves against it. Defaulting it silently is what
  // produced the wrong-SAR class of defect, so it is refused instead.
  const rc = (input.reportingCurrency ?? '').trim().toUpperCase();
  if (!rc) return { ok: false, reason: 'missing-currency' };
  if (!/^[A-Z]{3}$/.test(rc)) return { ok: false, reason: 'invalid-currency' };

  const id = (input.id ?? '').trim() || mintId('co');
  if (list.some(c => c.id === id)) return { ok: false, reason: 'duplicate-id' };

  const record: Company = {
    id,
    name,
    nameAr: input.nameAr?.trim() || undefined,
    logoUrl: input.logoUrl || undefined,
    status: input.status ?? 'Active',
    portfolioValue: Number(input.portfolioValue) || 0,
    sectors: 0,
    projects: 0,
    riskRating: input.riskRating ?? 'Low',
    compliance: input.compliance ?? 'Compliant',
    description: input.description?.trim() || undefined,
    primaryColor: input.primaryColor || undefined,
    secondaryColor: input.secondaryColor || undefined,
    reportingCurrency: rc,
    timeZone: input.timeZone?.trim() || undefined,
    calendar: input.calendar,
    country: input.country?.trim() ?? '',
    city: input.city?.trim() || undefined,
    headquarters: input.headquarters?.trim() || undefined,
    createdAt: nowIso(),
    createdBy: input.createdBy || 'unknown',
  };

  writeCompanies([...list, record]);
  // Keep the FX store — the AUTHORITY — in step from the first moment.
  writeReportingCurrencyToFx(id, rc);
  return { ok: true, record };
}

/**
 * Writes `baseCurrency` into the company's FX settings.
 *
 * The FX store is the authority every conversion reads; the field on the
 * Company record is only a mirror for display. This helper is the single
 * place the two are synchronised, so they cannot drift.
 *
 * It touches ONLY `baseCurrency` — the supported-currency list and every
 * published rate are preserved exactly as found. No rate is created,
 * altered or removed, and no historical figure changes.
 */
/**
 * Gives a company a reporting currency ONLY when it has none.
 *
 * Never overwrites: a company that already declares one keeps it, so this
 * is safe to call on every start-up and cannot restate a live setting.
 */
function ensureReportingCurrency(companyId: string, fallback: string): void {
  const existing = (() => {
    try {
      const raw = JSON.parse(localStorage.getItem(`pactum-currency-${companyId}`) || 'null');
      return String(raw?.baseCurrency ?? '').toUpperCase().slice(0, 3);
    } catch { return ''; }
  })();
  const code = existing || fallback;

  const list = readCompanies();
  const i = list.findIndex(c => c.id === companyId);
  if (i >= 0 && !list[i].reportingCurrency) {
    const out = list.slice();
    out[i] = { ...out[i], reportingCurrency: code };
    writeJson(COMPANIES_KEY, out);   // no notify: seeding, not a user edit
  }
  if (!existing) writeReportingCurrencyToFx(companyId, code);
}

function writeReportingCurrencyToFx(companyId: string, code: string): void {
  try {
    const key = `pactum-currency-${companyId}`;
    const raw = JSON.parse(localStorage.getItem(key) || 'null');
    const next = (raw && typeof raw === 'object')
      ? { ...raw, baseCurrency: code }
      : { baseCurrency: code, currencies: [] };
    localStorage.setItem(key, JSON.stringify(next));
  } catch { /* quota — the mirror on the record still records intent */ }
}

/**
 * Sets a company's reporting currency — Task 4.
 *
 * FORWARD-LOOKING ONLY. Not one stored amount is rewritten: every
 * historical figure keeps the `appliedRate` frozen at the moment it was
 * captured, and every approved Timeline snapshot keeps the reporting
 * currency it was archived under. Changing this alters what FUTURE
 * reporting converts into, and nothing else — which is exactly what the
 * brief requires.
 */
export function setReportingCurrency(
  companyId: string, code: string,
): MdResult<Company> {
  const list = readCompanies();
  const i = list.findIndex(c => c.id === companyId);
  if (i < 0) return { ok: false, reason: 'not-found' };

  const rc = (code || '').trim().toUpperCase();
  if (!rc) return { ok: false, reason: 'missing-currency' };
  if (!/^[A-Z]{3}$/.test(rc)) return { ok: false, reason: 'invalid-currency' };

  const next: Company = { ...list[i], reportingCurrency: rc };
  const out = list.slice();
  out[i] = next;
  writeCompanies(out);
  writeReportingCurrencyToFx(companyId, rc);
  return { ok: true, record: next };
}

export type UpdateCompanyInput = Partial<Omit<Company, 'id' | 'createdAt' | 'createdBy'>>;

/**
 * Renames / edits a company.
 *
 * Because every consumer now reads this store, a rename here IS the
 * propagation — there is no second copy to keep in step.
 */
export function updateCompany(id: string, patch: UpdateCompanyInput): MdResult<Company> {
  const list = readCompanies();
  const i = list.findIndex(c => c.id === id);
  if (i < 0) return { ok: false, reason: 'not-found' };

  if (patch.name !== undefined) {
    const name = patch.name.trim();
    if (!name) return { ok: false, reason: 'missing-name' };
    if (list.some(c => c.id !== id && sameName(c.name, name))) {
      return { ok: false, reason: 'duplicate-name' };
    }
  }

  const next: Company = {
    ...list[i],
    ...patch,
    name: patch.name !== undefined ? patch.name.trim() : list[i].name,
    id: list[i].id,
    createdAt: list[i].createdAt,
    createdBy: list[i].createdBy,
  };

  const out = list.slice();
  out[i] = next;
  writeCompanies(out);
  return { ok: true, record: next };
}

/**
 * Archives a company.
 *
 * ══════════════════════════════════════════════════════════════════════
 * SPRINT 2 — ARCHIVE IS NOT DELETE
 *
 * `EntityStatus` already carried 'Archived' and `deleteCompany` already
 * refused while dependents existed — but nothing could actually MOVE a
 * company into the archived state. The status was declared and
 * unreachable.
 *
 * Archiving is the answer to "I cannot delete this because it has
 * sectors, but I do not want to see it any more". So unlike delete it is
 * ALLOWED with children: the whole point is to retire a company whose
 * history must stay readable.
 *
 * What it refuses is archiving a company that still has ACTIVE sectors,
 * because that would hide a parent while its children stay live in
 * pickers — the user would see orphan-looking sectors with no company.
 * Archive the sectors first, or use `cascade` to archive them together.
 *
 * Nothing is deleted. No storage key is touched. Reversible via
 * `restoreCompany`.
 * ══════════════════════════════════════════════════════════════════════
 */
export function archiveCompany(
  id: string, by = 'unknown', opts: { cascade?: boolean } = {},
): MdResult<Company> {
  const list = readCompanies();
  const i = list.findIndex(c => c.id === id);
  if (i < 0) return { ok: false, reason: 'not-found' };
  if (list[i].status === 'Archived') {
    return { ok: false, reason: 'already-archived', record: list[i] };
  }

  const sectors = readSectors().filter(s => s.companyId === id);
  const activeSectors = sectors.filter(s => s.status !== 'Archived');

  if (activeSectors.length > 0 && !opts.cascade) {
    return {
      ok: false,
      reason: 'has-active-children',
      blockers: [`${activeSectors.length} active sector(s): ${activeSectors.map(s => s.name).join(', ')}`],
    };
  }

  // Cascade: children first, so a failure part-way cannot leave an
  // archived parent above live children.
  if (opts.cascade && activeSectors.length > 0) {
    const all = readSectors();
    writeSectors(all.map(s =>
      s.companyId === id && s.status !== 'Archived'
        ? { ...s, status: 'Archived' as EntityStatus }
        : s));
  }

  const next: Company = { ...list[i], status: 'Archived' };
  const out = list.slice();
  out[i] = next;
  writeCompanies(out);
  return { ok: true, record: next };
}

/**
 * Restores an archived company to Active.
 *
 * Sectors are NOT restored with it. A cascade archive was a deliberate
 * bulk action; a cascade restore would silently revive sectors the user
 * may have archived individually beforehand, and there is no record of
 * which state each was in. They are restored one at a time, visibly.
 */
export function restoreCompany(id: string): MdResult<Company> {
  const list = readCompanies();
  const i = list.findIndex(c => c.id === id);
  if (i < 0) return { ok: false, reason: 'not-found' };
  if (list[i].status !== 'Archived') {
    return { ok: false, reason: 'not-archived', record: list[i] };
  }
  const next: Company = { ...list[i], status: 'Active' };
  const out = list.slice();
  out[i] = next;
  writeCompanies(out);
  return { ok: true, record: next };
}

/** Companies excluding archived — what every picker should show. */
export function activeCompanies(): Company[] {
  return readCompanies().filter(c => c.status !== 'Archived');
}

/**
 * Deletes a company — REFUSED while anything depends on it.
 *
 * Two levels are checked, because either one left behind would be an
 * orphan: the company's sectors, and any project pointing at the company
 * directly. The blockers are returned by name so the UI can tell the user
 * what to clear first instead of just refusing.
 */
export function deleteCompany(id: string, projects: ProjectLink[] = []): MdResult<Company> {
  const list = readCompanies();
  const target = list.find(c => c.id === id);
  if (!target) return { ok: false, reason: 'not-found' };

  const sectors = readSectors().filter(s => s.companyId === id);
  const directProjects = projects.filter(p => p.companyId === id);
  const sectorIds = new Set(sectors.map(s => s.id));
  const viaSector = projects.filter(p => p.sectorId && sectorIds.has(p.sectorId));

  const projectCount = new Set([
    ...directProjects.map(p => p.id),
    ...viaSector.map(p => p.id),
  ]).size;

  if (sectors.length > 0 || projectCount > 0) {
    const blockers: string[] = [];
    if (sectors.length) blockers.push(`${sectors.length} sector(s): ${sectors.map(s => s.name).join(', ')}`);
    if (projectCount) blockers.push(`${projectCount} project(s)`);
    return { ok: false, reason: 'has-dependents', blockers };
  }

  writeCompanies(list.filter(c => c.id !== id));
  return { ok: true, record: target };
}

// ── SECTOR CRUD ────────────────────────────────────────────────────────

export interface CreateSectorInput {
  name: string;
  nameAr?: string;
  companyId: string;
  /** Optional. Empty inherits the company reporting currency. */
  defaultContractCurrency?: string;
  /**
   * MANDATORY — the unit this sector's analytics are reported in.
   * A sector that cannot state its currency cannot state a total, so
   * creation is refused rather than defaulted.
   */
  reportingCurrency: string;
  status?: EntityStatus;
  createdBy?: string;
  id?: string;
}

/**
 * Creates a sector under a company.
 *
 * Duplicate names are refused WITHIN THE PARENT only — two different
 * companies may both have an "Infrastructure" sector, and refusing that
 * would be wrong. Uniqueness is scoped to where the ambiguity actually
 * exists.
 */
export function createSector(input: CreateSectorInput): MdResult<Sector> {
  const name = (input.name ?? '').trim();
  const companyId = (input.companyId ?? '').trim();

  if (!name) return { ok: false, reason: 'missing-name' };
  if (!companyId) return { ok: false, reason: 'missing-company' };
  if (!findCompanyById(companyId)) return { ok: false, reason: 'company-not-found' };

  // The reporting currency is mandatory: every figure on this sector's
  // screens is converted into it, and a missing unit is what produced
  // totals labelled with a currency nobody chose.
  const reportingCurrency = (input.reportingCurrency ?? '').trim().toUpperCase();
  if (!reportingCurrency) return { ok: false, reason: 'missing-currency' };
  if (!/^[A-Z]{3}$/.test(reportingCurrency)) {
    return { ok: false, reason: 'invalid-currency' };
  }

  const list = readSectors();
  const siblings = list.filter(s => s.companyId === companyId);
  if (siblings.some(s => sameName(s.name, name))) {
    return { ok: false, reason: 'duplicate-name' };
  }

  const id = (input.id ?? '').trim() || mintId('sec');
  if (list.some(s => s.id === id)) return { ok: false, reason: 'duplicate-id' };

  const record: Sector = {
    id,
    name,
    nameAr: input.nameAr?.trim() || undefined,
    companyId,
    status: input.status ?? 'Active',
    projectIds: [],
    defaultContractCurrency:
      (input.defaultContractCurrency ?? '').trim().toUpperCase() || undefined,
    reportingCurrency,
    // Appended to the end of its own company's list.
    order: siblings.length,
    createdAt: nowIso(),
    createdBy: input.createdBy || 'unknown',
  };

  writeSectors([...list, record]);
  return { ok: true, record };
}

export type UpdateSectorInput = Partial<
  Omit<Sector, 'id' | 'createdAt' | 'createdBy' | 'projectIds'>
>;

/**
 * Renames / edits a sector.
 *
 * Moving a sector to another company is permitted, but the duplicate-name
 * check then runs against the DESTINATION company's siblings — otherwise a
 * move could quietly create the collision that `createSector` refuses.
 */
export function updateSector(id: string, patch: UpdateSectorInput): MdResult<Sector> {
  const list = readSectors();
  const i = list.findIndex(s => s.id === id);
  if (i < 0) return { ok: false, reason: 'not-found' };

  const current = list[i];
  const destCompany = patch.companyId?.trim() || current.companyId;

  if (patch.companyId !== undefined && !findCompanyById(destCompany)) {
    return { ok: false, reason: 'company-not-found' };
  }

  if (patch.name !== undefined || patch.companyId !== undefined) {
    const name = (patch.name ?? current.name).trim();
    if (!name) return { ok: false, reason: 'missing-name' };
    const clash = list.some(s =>
      s.id !== id && s.companyId === destCompany && sameName(s.name, name));
    if (clash) return { ok: false, reason: 'duplicate-name' };
  }

  const next: Sector = {
    ...current,
    ...patch,
    name: patch.name !== undefined ? patch.name.trim() : current.name,
    companyId: destCompany,
    id: current.id,
    projectIds: current.projectIds,
    createdAt: current.createdAt,
    createdBy: current.createdBy,
  };

  const out = list.slice();
  out[i] = next;
  writeSectors(out);
  return { ok: true, record: next };
}

/**
 * Deletes a sector — REFUSED while any project belongs to it.
 *
 * Checked against the LIVE projects array rather than the cached
 * `projectIds`, because the cache is derived and could be stale. The
 * authoritative answer is "does a project point here right now".
 */
export function deleteSector(id: string, projects: ProjectLink[] = []): MdResult<Sector> {
  const list = readSectors();
  const target = list.find(s => s.id === id);
  if (!target) return { ok: false, reason: 'not-found' };

  const owned = projects.filter(p => p.sectorId === id);
  if (owned.length > 0) {
    return {
      ok: false,
      reason: 'has-dependents',
      blockers: [`${owned.length} project(s)`],
    };
  }

  const remaining = list.filter(s => s.id !== id);
  // Close the gap so ordering stays contiguous within the parent company.
  const resequenced = remaining.map(s =>
    s.companyId === target.companyId && s.order > target.order
      ? { ...s, order: s.order - 1 }
      : s);

  writeSectors(resequenced);
  return { ok: true, record: target };
}

/**
 * Moves a sector up or down within its company.
 *
 * Ordering is per-company and always contiguous from 0. A move past either
 * end is a no-op returning ok:true — the user asked for something already
 * true, which is not an error.
 */
/**
 * Archives a sector.
 *
 * SPRINT 2. Same reasoning as `archiveCompany`: 'Archived' was a legal
 * `EntityStatus` with no way to reach it.
 *
 * Refused while ACTIVE (non-archived) projects still sit in the sector,
 * because hiding the parent would strand them in the project picker with
 * no visible sector. `projects` is passed in rather than read here — the
 * project store is owned by projectMaster, and reaching across would give
 * this module two sources of truth for the same fact.
 *
 * The sector keeps its `projectIds` cache untouched, so restoring it
 * brings back exactly the same membership.
 */
export function archiveSector(
  id: string, projects: ProjectLink[] = [], by = 'unknown', note = '',
): MdResult<Sector> {
  const list = readSectors();
  const i = list.findIndex(s => s.id === id);
  if (i < 0) return { ok: false, reason: 'not-found' };
  if (list[i].status === 'Archived') {
    return { ok: false, reason: 'already-archived', record: list[i] };
  }

  // `status` now travels on ProjectLink. Absent is read as ACTIVE, which
  // is the conservative reading: an unknown project should block an
  // archive rather than be silently ignored.
  const live = projects.filter(
    p => p.sectorId === id && p.status !== 'Archived',
  );
  if (live.length > 0) {
    return {
      ok: false,
      reason: 'has-active-children',
      blockers: [`${live.length} active project(s)`],
    };
  }

  const at = new Date().toISOString();
  const next: Sector = {
    ...list[i],
    status: 'Archived',
    archivedAt: at,
    archivedBy: by || 'unknown',
    archiveLog: [
      ...(list[i].archiveLog || []),
      { action: 'archived', at, by: by || 'unknown', note: String(note || '') },
    ],
  };
  const out = list.slice();
  out[i] = next;
  writeSectors(out);
  return { ok: true, record: next };
}

/**
 * Restores an archived sector.
 *
 * Refused when the parent company is itself archived — restoring a child
 * under a hidden parent produces exactly the orphan state the archive
 * guards exist to prevent. Restore the company first.
 */
export function restoreSector(id: string, by = 'unknown', note = ''): MdResult<Sector> {
  const list = readSectors();
  const i = list.findIndex(s => s.id === id);
  if (i < 0) return { ok: false, reason: 'not-found' };
  if (list[i].status !== 'Archived') {
    return { ok: false, reason: 'not-archived', record: list[i] };
  }

  const parent = findCompanyById(list[i].companyId);
  if (parent && parent.status === 'Archived') {
    return {
      ok: false,
      reason: 'has-active-children',
      blockers: [`parent company "${parent.name}" is archived — restore it first`],
    };
  }

  // The archive EVENT survives the restore. Only the current-state
  // fields are cleared, because a restored sector is not archived.
  const log = (list[i].archiveLog || []).slice();
  if (log.length === 0 && list[i].archivedAt) {
    log.push({ action: 'archived', at: list[i].archivedAt as string,
               by: list[i].archivedBy || 'unknown', note: '' });
  }
  log.push({ action: 'restored', at: new Date().toISOString(), by: by || 'unknown', note: String(note || '') });

  const { archivedAt, archivedBy, ...rest } = list[i];
  const next: Sector = { ...rest, status: 'Active', archiveLog: log };
  const out = list.slice();
  out[i] = next;
  writeSectors(out);
  return { ok: true, record: next };
}

/** Sectors of one company excluding archived. */
export function activeSectorsOf(companyId: string): Sector[] {
  return readSectors()
    .filter(s => s.companyId === companyId && s.status !== 'Archived')
    .sort((a, b) => a.order - b.order);
}

export function reorderSector(id: string, direction: 'up' | 'down'): MdResult<Sector> {
  const list = readSectors();
  const target = list.find(s => s.id === id);
  if (!target) return { ok: false, reason: 'not-found' };

  const siblings = list
    .filter(s => s.companyId === target.companyId)
    .sort((a, b) => a.order - b.order);

  const pos = siblings.findIndex(s => s.id === id);
  const swapWith = direction === 'up' ? pos - 1 : pos + 1;
  if (swapWith < 0 || swapWith >= siblings.length) {
    return { ok: true, record: target };
  }

  const a = siblings[pos];
  const b = siblings[swapWith];
  const out = list.map(s => {
    if (s.id === a.id) return { ...s, order: b.order };
    if (s.id === b.id) return { ...s, order: a.order };
    return s;
  });

  writeSectors(out);
  return { ok: true, record: { ...a, order: b.order } };
}

/** Explicit ordering for a whole company, e.g. after a drag. */
export function setSectorOrder(companyId: string, orderedIds: string[]): MdResult<Sector[]> {
  const list = readSectors();
  const siblings = list.filter(s => s.companyId === companyId);
  if (siblings.length !== orderedIds.length) return { ok: false, reason: 'invalid-order' };
  if (!siblings.every(s => orderedIds.includes(s.id))) return { ok: false, reason: 'invalid-order' };

  const rank = new Map(orderedIds.map((id, i) => [id, i]));
  const out = list.map(s =>
    s.companyId === companyId ? { ...s, order: rank.get(s.id) ?? s.order } : s);
  writeSectors(out);
  return { ok: true };
}

// ── RECONCILIATION ─────────────────────────────────────────────────────

export interface ReconcileReport {
  /** Projects with no company or no sector. */
  orphanProjects: string[];
  /** Sectors whose companyId points at nothing. */
  orphanSectors: string[];
  /** Projects whose sectorId points at nothing. */
  danglingSector: string[];
  /** Projects whose companyId disagrees with their sector's company. */
  mismatched: string[];
  /** projectIds entries that no longer correspond to a real project. */
  staleLinks: number;
  /** True when the cached projectIds needed rewriting. */
  repaired: boolean;
}

/**
 * Rebuilds `Sector.projectIds` from the projects array and reports every
 * integrity violation found on the way.
 *
 * DERIVED, NOT AUTHORITATIVE. `Project.sectorId` is the truth; this only
 * refreshes the cache the older call sites read. Nothing is deleted and no
 * project is reassigned — a mismatch is REPORTED so a human can decide,
 * because silently moving a project between companies would be exactly the
 * kind of invisible data change this platform refuses to make.
 */
export function reconcile(projects: ProjectLink[]): ReconcileReport {
  const companies = readCompanies();
  const sectors = readSectors();
  const companyIds = new Set(companies.map(c => c.id));
  const sectorById = new Map(sectors.map(s => [s.id, s]));
  const projectIds = new Set(projects.map(p => p.id));

  const orphanProjects: string[] = [];
  const danglingSector: string[] = [];
  const mismatched: string[] = [];

  const bySector = new Map<string, string[]>();

  projects.forEach(p => {
    if (!p.sectorId || !p.companyId) { orphanProjects.push(p.id); return; }
    const sec = sectorById.get(p.sectorId);
    if (!sec) { danglingSector.push(p.id); return; }
    if (sec.companyId !== p.companyId) mismatched.push(p.id);
    bySector.set(p.sectorId, [...(bySector.get(p.sectorId) ?? []), p.id]);
  });

  const orphanSectors = sectors
    .filter(s => !companyIds.has(s.companyId))
    .map(s => s.id);

  // Count cached links that point at projects which no longer exist.
  let staleLinks = 0;
  sectors.forEach(s => {
    s.projectIds.forEach(pid => { if (!projectIds.has(pid)) staleLinks++; });
  });

  const nextSectors = sectors.map(s => ({
    ...s,
    projectIds: bySector.get(s.id) ?? [],
  }));

  const changed = JSON.stringify(sectors.map(s => s.projectIds))
    !== JSON.stringify(nextSectors.map(s => s.projectIds));
  if (changed) writeSectors(nextSectors);

  // Refresh the presentation counters on the company records.
  const countsChanged = refreshCompanyCounts(nextSectors, projects);

  return {
    orphanProjects,
    orphanSectors,
    danglingSector,
    mismatched,
    staleLinks,
    repaired: changed || countsChanged,
  };
}

/** Keeps `company.sectors` / `company.projects` honest. Presentation only. */
function refreshCompanyCounts(sectors: Sector[], projects: ProjectLink[]): boolean {
  const list = readCompanies();
  const next = list.map(c => {
    const secs = sectors.filter(s => s.companyId === c.id);
    const projCount = projects.filter(p => p.companyId === c.id).length;
    return { ...c, sectors: secs.length, projects: projCount };
  });
  const changed = JSON.stringify(list) !== JSON.stringify(next);
  if (changed) writeCompanies(next);
  return changed;
}

// ── VALIDATION ─────────────────────────────────────────────────────────

export interface ValidationIssue {
  level: 'error' | 'warning';
  code:
    | 'orphan-project' | 'orphan-sector' | 'dangling-sector'
    | 'company-mismatch' | 'duplicate-company-id' | 'duplicate-sector-id'
    | 'duplicate-project-id' | 'duplicate-company-name'
    | 'duplicate-sector-name' | 'missing-name';
  message: string;
  ids: string[];
}

/**
 * Full referential sweep. Read-only — never repairs, only reports.
 *
 * `error` means the data is inconsistent and a screen will misbehave.
 * `warning` means it is legal but suspicious.
 */
export function validateMasterData(projects: ProjectLink[] = []): ValidationIssue[] {
  const issues: ValidationIssue[] = [];
  const companies = readCompanies();
  const sectors = readSectors();

  const push = (level: ValidationIssue['level'], code: ValidationIssue['code'],
                message: string, ids: string[]) => {
    if (ids.length) issues.push({ level, code, message, ids });
  };

  // ── Duplicate ids ──
  const dupIds = (arr: { id: string }[]) => {
    const seen = new Set<string>(); const dup = new Set<string>();
    arr.forEach(x => { if (seen.has(x.id)) dup.add(x.id); seen.add(x.id); });
    return Array.from(dup);
  };
  push('error', 'duplicate-company-id', 'Duplicate company id', dupIds(companies));
  push('error', 'duplicate-sector-id', 'Duplicate sector id', dupIds(sectors));
  push('error', 'duplicate-project-id', 'Duplicate project id', dupIds(projects));

  // ── Duplicate names inside the same parent ──
  const dupCompanyNames = new Set<string>();
  companies.forEach((c, i) => {
    if (companies.some((o, j) => j !== i && sameName(o.name, c.name))) {
      dupCompanyNames.add(c.name);
    }
  });
  push('error', 'duplicate-company-name',
       'Two companies share a name', Array.from(dupCompanyNames));

  const dupSectorNames: string[] = [];
  const byCompany = new Map<string, Sector[]>();
  sectors.forEach(s => byCompany.set(s.companyId, [...(byCompany.get(s.companyId) ?? []), s]));
  byCompany.forEach((group, cid) => {
    group.forEach((s, i) => {
      if (group.some((o, j) => j !== i && sameName(o.name, s.name))) {
        dupSectorNames.push(`${cid}/${s.name}`);
      }
    });
  });
  push('error', 'duplicate-sector-name',
       'Two sectors share a name inside one company', Array.from(new Set(dupSectorNames)));

  // ── Missing names ──
  push('error', 'missing-name', 'Record has no name', [
    ...companies.filter(c => !c.name.trim()).map(c => c.id),
    ...sectors.filter(s => !s.name.trim()).map(s => s.id),
  ]);

  // ── Referential integrity ──
  const companyIds = new Set(companies.map(c => c.id));
  const sectorById = new Map(sectors.map(s => [s.id, s]));

  push('error', 'orphan-sector', 'Sector points at a company that does not exist',
       sectors.filter(s => !companyIds.has(s.companyId)).map(s => s.id));

  push('error', 'orphan-project', 'Project has no company or no sector',
       projects.filter(p => !p.companyId || !p.sectorId).map(p => p.id));

  push('error', 'dangling-sector', 'Project points at a sector that does not exist',
       projects.filter(p => p.sectorId && !sectorById.has(p.sectorId)).map(p => p.id));

  push('error', 'company-mismatch',
       "Project's company disagrees with its sector's company",
       projects.filter(p => {
         if (!p.sectorId || !p.companyId) return false;
         const s = sectorById.get(p.sectorId);
         return !!s && s.companyId !== p.companyId;
       }).map(p => p.id));

  return issues;
}

/** Convenience: true when nothing is broken. */
export function isMasterDataValid(projects: ProjectLink[] = []): boolean {
  return validateMasterData(projects).every(i => i.level !== 'error');
}

// ── Name resolution helpers ────────────────────────────────────────────

/** Display name for a company id, or a dash. Never invents a name. */
export function companyNameOf(id: string, lang: 'en' | 'ar' = 'en'): string {
  const c = findCompanyById(id);
  if (!c) return '—';
  return (lang === 'ar' && c.nameAr) ? c.nameAr : c.name;
}

/** Display name for a sector id, or a dash. */
export function sectorNameOf(id: string, lang: 'en' | 'ar' = 'en'): string {
  const s = findSectorById(id);
  if (!s) return '—';
  return (lang === 'ar' && s.nameAr) ? s.nameAr : s.name;
}


// ── Currency resolution across the hierarchy ───────────────────────────

/**
 * The company's reporting currency — Task 4/5.
 *
 * Reads the FX store, which is the AUTHORITY every conversion uses, and
 * falls back to the mirror on the Company record only when the FX store
 * has no entry yet. Returns '' rather than guessing 'SAR': a caller that
 * needs a default should say so explicitly, because a silent SAR is
 * precisely the defect Phase 3E traced through six modules.
 */
export function reportingCurrencyOfCompany(companyId: string): string {
  if (!companyId) return '';
  try {
    const raw = JSON.parse(localStorage.getItem(`pactum-currency-${companyId}`) || 'null');
    const base = String(raw?.baseCurrency ?? '').toUpperCase().slice(0, 3);
    if (base) return base;
  } catch { /* fall through to the mirror */ }
  return findCompanyById(companyId)?.reportingCurrency ?? '';
}

/**
 * The contract currency a NEW project in this sector should default to.
 *
 * Sector default first, then the company's reporting currency. Used only
 * to pre-fill the create form — the user may still override, and an
 * existing project is never affected.
 */
export function defaultContractCurrencyFor(
  companyId: string, sectorId?: string,
): string {
  const sec = sectorId ? findSectorById(sectorId) : undefined;
  return sec?.defaultContractCurrency || reportingCurrencyOfCompany(companyId);
}
